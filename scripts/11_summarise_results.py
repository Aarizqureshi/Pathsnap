"""Collect every experiment output into one report-ready markdown file.

Reads the CSV/JSON files written by scripts 05-09 and writes
results/summary.md with the tables the report needs (model comparison,
tuned vs untuned, HMM comparison). Nothing is typed by hand, so the report
tables always match the repository.

Usage:  python scripts/11_summarise_results.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd

from pathsnap import config

R = config.RESULTS_DIR


def md(df: pd.DataFrame, digits=4) -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: f"{v:.{digits}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def main():
    parts = ["# PathSnap results summary", "",
             "Generated by `scripts/11_summarise_results.py` from the files in `results/`.", ""]

    comp = pd.read_csv(R / "models" / "comparison.csv")
    t = comp[["model", "family", "config", "cv_f1_macro_mean", "cv_f1_macro_std", "cv_top1_mean",
              "test_top1", "test_route_continuity", "test_route_continuity_3hop", "test_f1_macro",
              "test_log_loss", "train_f1_macro", "fit_s", "predict_ms_per_1k_obs"]]
    parts += ["## 1. Model comparison (student-test unless marked CV)", "", md(t), ""]
    sel = json.loads((R / "models" / "selected_model.json").read_text())
    parts += [f"Selected model: **{sel['selected']}**. Rule: {sel['rule']}.", ""]

    best = json.loads((R / "tuning" / "best_params.json").read_text())
    parts += ["## 2. Bayesian optimisation", "",
              f"- Model: {best['model']}, sampler: {best['sampler']}, trials: {best['n_trials']}, "
              f"search time: {best['search_seconds'] / 60:.1f} min",
              f"- Objective: {best['objective']}",
              f"- Best parameters: `{json.dumps(best['best_params'])}` (CV top-1 {best['best_cv_top1']:.4f})", ""]
    tv = pd.read_csv(R / "tuning" / "tuned_vs_untuned.csv")
    parts += [md(tv[["model", "cv_f1_macro", "test_top1", "test_f1_macro", "test_log_loss",
                     "inference_s", "fit_s"]]), ""]

    hm = pd.read_csv(R / "hmm" / "student_test_summary.csv")
    hcfg = json.loads((config.HMM_CONFIG_PATH).read_text())
    parts += ["## 3. HMM / Viterbi", "",
              f"Decoder parameters: `{json.dumps(hcfg['params'])}`, tuned on {hcfg['tuned_on']}.", "",
              md(hm), ""]
    per = pd.read_csv(R / "hmm" / "student_test_per_trip.csv", dtype={"trip_id": str})
    parts += ["Per trip:", "", md(per[["trip_id", "n_valid_labels", "top1_classifier", "top1_hmm", "top1_gain",
                                       "discontinuities_classifier", "discontinuities_hmm", "hmm_breaks",
                                       "predict_s"]]), ""]
    worse = per[per["top1_gain"] < 0]
    parts += [f"Trips where HMM lowered top-1: {', '.join(worse['trip_id']) if len(worse) else 'none'}.", ""]

    out = R / "summary.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print("saved", out)


if __name__ == "__main__":
    main()
